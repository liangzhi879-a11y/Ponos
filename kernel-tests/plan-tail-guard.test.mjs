// 计划尾守卫判据回归（2026-09-16 口径收紧）
// ---------------------------------------------------------------------------
// 背景：活跃度巡检实测「计划尾注入」是第二高频的循环守卫注入（近 3 天 29 次），而
// `isPlanTail` 此前**零测试覆盖**（kernel-tests 内 grep 命中 0）。误伤代价不对称：
// 命中即注入"你承诺了后续动作…"并**清空 textBuf**（见 engine.mjs 计划尾分支）——
// 已流式展示给用户的那段内容不落 transcript、被重新生成，同时把正常收尾强行拉回
// 工具轮；漏检只少一次推进指令，用户可发「继续」。故按"宁漏勿滥"重新划界：
//   · 删掉无动作指向 / 对用户说话的裸词：`计划`（交付物名称）、`准备(好)?`（"已准备
//     就绪"）、`稍等`/`待会`/`稍后`（客套话）、`再(继续|检查|验证|读|看)`（结论性说明）；
//   · 保留的分支都要求"后续动作动词"或"第一人称承诺主语"。
// 本文件把两侧都钉死：**误伤面**（应判 false）与**真计划尾**（应判 true）。
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { isPlanTail, PLAN_TAIL_RE, PLAN_TAIL_DONE_RE } from '../kernel/gen-guards.mjs'

// ---------------------------------------------------------------------------
// ★ 误伤回归：这些是"正常收尾/交付说明/对用户说话"，一律不得命中
// ---------------------------------------------------------------------------
test('误伤回归：中文正常收尾与交付说明不得判为计划尾', () => {
  const safe = [
    // 交付物名称含"计划"（申报/咨询材料场景的高频误伤源）
    '这是本次高新技术企业申报的整理计划，已按材料类型分好目录。',
    '本项目实施计划如下：四个阶段，全部材料已归档。',
    '研发立项报告与项目计划书均已整理完毕。',
    // "准备"作状态而非承诺
    '材料已准备就绪，可以提交了。',
    '数据准备完成，无缺失项。',
    // 客套话/时长说明（对用户说话，不是承诺后续动作）
    '生成完整报告需要稍等片刻。',
    '稍后可以再问我细节。',
    '这部分统计稍后会在附录里体现。',
    // "再…"作结论性补充说明
    '这部分可以再检查一下，但结论已经明确。',
    // 无任何计划措辞的普通收尾
    '检查已完成，内核守卫未发现异常。',
    '共核对 12 项，全部一致。',
  ]
  for (const t of safe) {
    assert.equal(isPlanTail(t), false, `不应判为计划尾：${JSON.stringify(t)}`)
  }
})

test('误伤回归：完成语优先否决（含新增收尾措辞）', () => {
  const done = [
    '接下来我读完了这三个文件，任务已完成。',
    '我先检查了一遍，没有发现问题，以上就是全部结论。',
    '下一步的处理已处理好，无需继续。',
    '让我先解释一下：这项工作 done 了。',
  ]
  for (const t of done) {
    assert.equal(isPlanTail(t), false, `完成语应否决计划尾：${JSON.stringify(t)}`)
  }
})

// ---------------------------------------------------------------------------
// ★ 真计划尾：这些必须仍被抓（证明收紧没有把守卫改废）
// ---------------------------------------------------------------------------
test('真计划尾：带后续动作动词/第一人称承诺的仍须命中', () => {
  const tails = [
    '接下来我要读取核心表格并核对数据。',
    '先读一下 engine.mjs 的守卫实现。',
    '先检查一下配置文件的默认值。',
    '我先看一下项目结构。',
    '让我先确认下现有测试的覆盖范围。',
    '需要先了解仓库的目录布局。',
    '开始实施重构，先从分歧最大的模块入手。',
    '下一步处理失败自愈的口径问题。',
    '立即开始执行批量修复。',
    // 英文形态
    'Let me start by reading the guard implementation.',
    'Next, I will examine the configuration.',
  ]
  for (const t of tails) {
    assert.equal(isPlanTail(t), true, `应判为计划尾：${JSON.stringify(t)}`)
  }
})

// ---------------------------------------------------------------------------
// 判据结构：被删分支不得回潮（防"顺手加回一个裸词"）
// ---------------------------------------------------------------------------
test('判据结构：无动作指向的裸词分支不得回潮', () => {
  // 逐个裸词构造"只含该裸词"的尾部——若有人把分支加回，这里必然命中
  const bares = ['稍等', '待会', '稍后', '计划', '准备好', '再继续']
  for (const b of bares) {
    assert.equal(isPlanTail(`好的。${b}`), false, `裸词 "${b}" 不得单独构成计划尾（误伤源）`)
  }
  // 反向前提：正则本身仍在工作（防"正则被整段删空"时上述断言全部空过）
  assert.ok(PLAN_TAIL_RE instanceof RegExp, 'PLAN_TAIL_RE 必须是正则')
  assert.match('先读一下文件', PLAN_TAIL_RE)
  assert.doesNotMatch('稍等', PLAN_TAIL_RE)
  assert.match('已完成', PLAN_TAIL_DONE_RE)
})

test('窗口语义：只看尾部 120 字符（中段计划措辞不触发）', () => {
  const far = '先读一下文件。' + '（无关正文）'.repeat(40) + '以上是结论。'
  assert.ok(far.length > 200)
  assert.equal(isPlanTail(far), false, '计划措辞在中段（超出尾部窗口）不应触发')
})
